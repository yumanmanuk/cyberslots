export type MsgKey = keyof typeof zh;

const DICTS = { zh, en } as const;
type Lang = keyof typeof DICTS;

export type TParams = Record<string, string | number>;

/** Fill `{name}` placeholders; unknown placeholders are left literal. */
function interpolate(str: string, params?: TParams): string {
  if (!params) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

function lookup(lang: Lang, key: MsgKey, params?: TParams): string {
  return interpolate(DICTS[lang][key] ?? zh[key], params);
}

export function useT(): (key: MsgKey, params?: TParams) => string {
  const lang = useChatStore((s) => s.settings?.language ?? 'zh');
  return (key, params) => lookup(lang, key, params);
}

/**
 * Non-hook translate for use outside React (stores, event-time system
 * announcements). Reads the current language synchronously from settings;
 * generated text is NOT retro-translated when the language later changes.
 */
export function translate(key: MsgKey, params?: TParams): string {
  const lang = (useChatStore.getState().settings?.language ?? 'zh') as Lang;
  return lookup(lang, key, params);
}

